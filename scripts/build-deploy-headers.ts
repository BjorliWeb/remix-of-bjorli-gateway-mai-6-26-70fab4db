/**
 * Generate `public/_headers` for Cloudflare Pages based on the
 * current deploy environment.
 *
 * Production detection (in priority order):
 *   1. `SITE_URL === 'https://bjorli.no'`
 *   2. `CF_PAGES_BRANCH === 'main'`  (Cloudflare Pages production branch)
 *
 * If neither is true the deploy is treated as Preview/staging and the
 * file emits `X-Robots-Tag: noindex, nofollow` for every path so that
 * `*.pages.dev` preview hosts are never indexed even if a crawler
 * ignores `robots.txt`. SPA fallback continues to live in
 * `public/_redirects` — this file only sets response headers.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const PRODUCTION_SITE_URL = 'https://bjorli.no';
const PRODUCTION_BRANCH = 'main';

const siteUrl = process.env.SITE_URL;
const branch = process.env.CF_PAGES_BRANCH;

const isProduction =
  siteUrl === PRODUCTION_SITE_URL ||
  (!siteUrl && branch === PRODUCTION_BRANCH);

// Supabase project ref from supabase/config.toml (REST, storage, edge
// functions incl. webcam6-image, and realtime over wss).
const SUPABASE_HOST = 'bbcondnkfxkylfmlektf.supabase.co';

/**
 * Content-Security-Policy, shipped as Report-Only until violations have
 * been reviewed. Every external origin below is loaded by the site today:
 *   - GTM / GA4 (src/lib/analytics.ts), Ahrefs Analytics (index.html)
 *   - Cloudflare Turnstile (src/components/Turnstile.tsx)
 *   - Supabase REST/storage/functions/realtime (src/integrations/supabase)
 *   - Fnugg API (src/lib/integrations/fnugg.ts) + blog images
 *   - webcam.io widget (WebcamIoEmbed), IPCamLive iframes (WeatherWebcams)
 *   - Google Maps embed (GettingHere)
 * Fonts are self-hosted. Skiperformance and Outdooractive are plain links.
 */
const CSP = [
  "default-src 'self'",
  "script-src 'self' https://www.googletagmanager.com https://analytics.ahrefs.com https://challenges.cloudflare.com https://webcam.io",
  "style-src 'self' 'unsafe-inline'",
  `img-src 'self' data: blob: https://${SUPABASE_HOST} https://www.googletagmanager.com https://*.google-analytics.com https://fnugg.no https://*.fnugg.no https://webcam.io https://*.webcam.io`,
  "font-src 'self'",
  `connect-src 'self' https://${SUPABASE_HOST} wss://${SUPABASE_HOST} https://api.fnugg.no https://www.googletagmanager.com https://*.google-analytics.com https://*.analytics.google.com https://analytics.ahrefs.com https://challenges.cloudflare.com https://webcam.io https://*.webcam.io`,
  "media-src 'self' blob: https://webcam.io https://*.webcam.io",
  "frame-src https://challenges.cloudflare.com https://*.ipcamlive.com https://www.google.com https://webcam.io https://*.webcam.io",
  "worker-src 'self'",
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join('; ');

const productionHeaders = `# Cloudflare Pages headers — production (indexable).
# Generated by scripts/build-deploy-headers.ts. Do not hand-edit.

/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  X-Frame-Options: DENY
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()
  Content-Security-Policy-Report-Only: ${CSP}

# Vite emits content-hashed filenames into /assets/, so they never change.
# HTML, sitemap.xml, robots.txt, llms*.txt keep Cloudflare's default
# revalidating cache; do not add Cache-Control to /* (rules merge).
/assets/*
  Cache-Control: public, max-age=31536000, immutable

# Service worker must always be revalidated so updates roll out.
/sw.js
  Cache-Control: no-cache

# Legacy WordPress asset paths: dead /wp-content/* files must never be
# indexed even while they still return 404 or are served from cache.
/wp-content/*
  X-Robots-Tag: noindex, nofollow
/wp-includes/*
  X-Robots-Tag: noindex, nofollow
`;

const previewHeaders = `# Cloudflare Pages headers — preview/staging (NOT indexable).
# Generated by scripts/build-deploy-headers.ts. Do not hand-edit.
#
# SITE_URL=${siteUrl ?? ''}  CF_PAGES_BRANCH=${branch ?? ''}
# Treated as non-production: emitting X-Robots-Tag: noindex, nofollow
# so *.pages.dev hosts cannot be indexed by search engines or AI crawlers.

/*
  X-Robots-Tag: noindex, nofollow
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
`;

const body = isProduction ? productionHeaders : previewHeaders;
writeFileSync(resolve('public/_headers'), body);
console.log(
  `_headers written — ${isProduction ? 'PRODUCTION (indexable)' : 'PREVIEW (noindex)'}` +
    ` (SITE_URL=${siteUrl ?? 'unset'}, CF_PAGES_BRANCH=${branch ?? 'unset'}).`,
);